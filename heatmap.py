# Fonction pour convertir température en couleur
def get_color_from_grid(temp_grid):
    temp_grid = np.nan_to_num(temp_grid)
    temp_grid = cv2.normalize(temp_grid, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)
    return cv2.applyColorMap(temp_grid, cv2.COLORMAP_JET)

# Fonction pour générer la heatmap d'un quadrant
def generate_quadrant_heatmap(centre, rayons, nb_sections, valeurs):
    radii = np.array(rayons)
    angles = np.linspace(0, np.pi/2, nb_sections, endpoint=False)
    R, A = np.meshgrid(radii, angles)
    R = R.flatten()
    A = A.flatten()
    X = centre[0] + R * np.cos(A)
    Y = centre[1] - R * np.sin(A)
    values_flat = np.array(valeurs).flatten()
    grid_x, grid_y = np.mgrid[0:w, 0:h]
    grid_T = griddata((X, Y), values_flat, (grid_x, grid_y), method='cubic', fill_value=np.min(values_flat))
    grid_T = np.nan_to_num(grid_T)
    return get_color_from_grid(grid_T.T)

