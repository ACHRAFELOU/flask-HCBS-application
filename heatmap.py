# ==================== Tracer les heatmaps ====================
def tracer_sein(centre, valeurs_sein):
    heatmap_sein = np.zeros_like(img)
    for q_idx, quadrant_vals in enumerate(valeurs_sein):
        heatmap_quad = generate_quadrant_heatmap(centre, rayons, nb_sections, quadrant_vals)
        mask = np.zeros((h, w), np.uint8)
        cv2.ellipse(mask, centre, (rayons[0], rayons[0]), 0, *quadrant_angles[q_idx], 255, -1)
        heatmap_sein = cv2.bitwise_or(heatmap_sein, cv2.bitwise_and(heatmap_quad, heatmap_quad, mask=mask))
    return heatmap_sein

